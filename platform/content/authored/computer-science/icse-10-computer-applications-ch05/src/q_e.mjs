// ---- menu of number checks (t03)
export const srcQuiz = code(
  'import java.util.Scanner;',
  '',
  'public class QuizClub {',
  '    // Number checks for an imagined number-quiz club',
  '    public static void main(String[] args) {',
  '        Scanner sc = new Scanner(System.in);',
  '        System.out.println("1. Prime");',
  '        System.out.println("2. Perfect");',
  '        System.out.println("3. Armstrong");',
  '        System.out.println("Enter your choice and a number:");',
  '        int choice = sc.nextInt();',
  '        int n = sc.nextInt();',
  '        switch (choice) {',
  '            case 1:',
  '                int f = 0;',
  '                for (int i = 1; i <= n; i++)',
  '                    if (n % i == 0)',
  '                        f++;',
  '                if (f == 2)',
  '                    System.out.println(n + " is a prime number");',
  '                else',
  '                    System.out.println(n + " is not a prime number");',
  '                break;',
  '            case 2:',
  '                int s = 0;',
  '                for (int i = 1; i < n; i++)',
  '                    if (n % i == 0)',
  '                        s += i;',
  '                if (s == n)',
  '                    System.out.println(n + " is a perfect number");',
  '                else',
  '                    System.out.println(n + " is not a perfect number");',
  '                break;',
  '            case 3:',
  '                int t = n, digits = 0, arm = 0;',
  '                while (t > 0) {',
  '                    digits++;',
  '                    t = t / 10;',
  '                }',
  '                t = n;',
  '                while (t > 0) {',
  '                    int d = t % 10;',
  '                    arm += (int) Math.pow(d, digits);',
  '                    t = t / 10;',
  '                }',
  '                if (arm == n)',
  '                    System.out.println(n + " is an Armstrong number");',
  '                else',
  '                    System.out.println(n + " is not an Armstrong number");',
  '                break;',
  '            default:',
  '                System.out.println("Invalid choice");',
  '        }',
  '    }',
  '}',
);
