  '    }',
  '    public void show() {',
  '        System.out.println(holder + " has Rs " + balance);',
  '    }',
  '    public static void main(String[] args) {',
  '        Scanner sc = new Scanner(System.in);',
  '        CoopSaver a = new CoopSaver(sc.next(), sc.nextDouble());',
  '        a.deposit(sc.nextDouble());',
  '        boolean ok = a.withdraw(sc.nextDouble());',
  '        if (!ok)',
