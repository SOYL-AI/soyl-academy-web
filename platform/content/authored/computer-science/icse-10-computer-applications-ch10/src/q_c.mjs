  '        sum = sum + t;',
  '        count++;',
  '    }',
  '    public void report() {',
  '        System.out.println("Accepted = " + count + ", highest = " + highest + ", lowest = " + lowest);',
  '        System.out.println("Average = " + (count == 0 ? 0 : sum / count));',
  '    }',
  '    public static void main(String[] args) {',
  '        Scanner sc = new Scanner(System.in);',
  '        TempLog log = new TempLog();',
  '        int n = sc.nextInt();',
  '        for (int i = 0; i < n; i++)',
  '            log.record(sc.nextDouble());',
